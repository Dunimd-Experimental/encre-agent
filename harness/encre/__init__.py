#   * ``__all__`` is the frozen public surface and is unchanged by this file.
#   * Every entry in ``__all__`` is resolvable through ``__getattr__``.
#   * Importing a leaf (e.g. ``encre.contracts``) no longer drags in the agent,
#     the backends, or the loop.
# ---------------------------------------------------------------------------

