from __future__ import annotations

"""Skill registry.

Loads, stores, and resolves :class:`BundledSkillDefinition` entries.  Skills
may be registered programmatically or discovered from ``SKILL.md`` files on
disk (with YAML/legacy frontmatter).  Name and alias lookups honour a
source-priority scheme so that higher-precedence definitions win on conflict.

The registry supports two lookup paths:

1. **Direct registration** — a skill is constructed in Python code and
   passed to :meth:`register`, typically during application startup.
2. **Directory scanning** — :meth:`load_from_dir` walks a filesystem
   directory tree, parses YAML frontmatter from each ``SKILL.md``, and
   registers the resulting definitions.  Flat ``*.md`` files are only
   accepted directly under the skills root (the ``tool-*.md`` guide layout).

When two skills share the same name or alias, the one with higher source
priority (managed > user > project > bundled) is kept and the lower-priority
definition is silently discarded.
"""

import logging
import os
import re
from typing import Any

import yaml

from encre.skills.types import (
    _PRIORITY_ORDER,
    BundledSkillDefinition,
    SkillContext,
    SkillSource,
)

logger = logging.getLogger("encre.skills.registry")

_EXTENSIONS_HEADER_PATTERN = re.compile(
    r"\.\w+$",
    re.IGNORECASE,
)

_FRONTMATTER_PATTERN = re.compile(
    r"^---\s*\n(.*?)\n---\s*\n",
    re.MULTILINE | re.DOTALL,
)

_ALIASES_SEPARATOR = re.compile(r",\s*")


def _read_skill_source(filepath: str) -> str:
    """Read a skill markdown file, decrypting runtime-encrypted content.

    Bundled/user/project skill definitions are public plaintext and are
    returned unchanged: content starting with the YAML frontmatter marker
    (``---``) never reaches the decrypt path.  Skills auto-generated by the
    evolution subsystem are encrypted at rest by ``SkillVerifier`` via
    :mod:`encre.secure_io`, so decryption is attempted explicitly for anything
    that does not look like plaintext frontmatter.  Failures are logged rather
    than swallowed: a key mismatch must show up in the logs instead of
    silently dropping skills, while ordinary frontmatter-less markdown
    (README-style files) simply falls back to its raw content and is skipped
    by the frontmatter parser as before.
    """
    try:
        with open(filepath, encoding="utf-8") as f:
            content = f.read()
    except (OSError, UnicodeDecodeError):
        # I/O or encoding failures are non-fatal; return empty string so
        # the caller skips the file without raising.
        return ""
    if not content or content.startswith("---"):
        # Plaintext frontmatter files are returned as-is — no decryption
        # attempt, which avoids a spurious log warning on every normal skill.
        return content
    try:
        from encre.crypto import decrypt

        plain = decrypt(content.strip())
    except Exception as e:
        # If decryption fails the file is either not encrypted or encrypted
        # with a different key; log at debug level and return the raw content
        # so the frontmatter parser can still try to interpret it.
        logger.debug("Skill file %s is not decryptable: %s", filepath, e)
        return content
    if not plain:
        # An empty decryption result usually means the ciphertext was
        # corrupted; warn so the user can investigate.
        logger.warning("Decrypting skill file %s yielded empty content", filepath)
        return content
    logger.debug("Decrypted runtime skill file: %s", filepath)
    return plain


class EncreSkillRegistry:
    """In-memory registry of skills keyed by name and alias.

    Maintains two internal dictionaries:

    - ``_skills``: maps a canonical skill name to its
      :class:`BundledSkillDefinition`.
    - ``_aliases``: maps each alternative name (alias) to the canonical
      name of the skill it resolves to.

    Source-priority conflict resolution ensures that a user-provided skill
    always overrides a bundled one of the same name, without requiring
    explicit deduplication logic at registration time.
    """

    def __init__(self) -> None:
        """Initialize empty name and alias maps."""
        self._skills: dict[str, BundledSkillDefinition] = {}
        self._aliases: dict[str, str] = {}

    def register(self, skill: BundledSkillDefinition) -> None:
        """Register a skill, resolving name/alias conflicts by source priority.

        A new skill replaces an existing one only when its source has strictly
        higher priority (lower number in :data:`_PRIORITY_ORDER`).  Ties are
        resolved in favour of the first-registered definition, which
        prevents later bundles from accidentally clobbering user-managed
        overrides.
        """
        existing = self._skills.get(skill.name)
        if existing is not None:
            # Lower _PRIORITY_ORDER value = higher precedence.
            # A new skill only wins if it has strictly higher priority.
            new_priority = _PRIORITY_ORDER.get(skill.source, 3)
            old_priority = _PRIORITY_ORDER.get(existing.source, 3)
            if new_priority >= old_priority:
                return
        self._skills[skill.name] = skill
        for alias in skill.aliases:
            existing_alias = self._aliases.get(alias)
            if existing_alias is not None:
                existing_skill = self._skills.get(existing_alias)
                if existing_skill is not None:
                    # Same priority-resolution logic applied to alias
                    # conflicts: a new alias only wins if its source
                    # outranks the skill that currently owns it.
                    new_priority = _PRIORITY_ORDER.get(skill.source, 3)
                    old_priority = _PRIORITY_ORDER.get(existing_skill.source, 3)
                    if new_priority >= old_priority:
                        continue
            self._aliases[alias] = skill.name

    def unregister(self, name: str) -> BundledSkillDefinition | None:
        """Remove a skill by name, cleaning up its aliases.

        Used by the verification gate to roll back an auto-generated skill and
        by legacy migration to stop injecting unverified artifacts.

        Args:
            name: The exact skill name to remove.

        Returns:
            The removed definition, or ``None`` when no such skill exists.
        """
        skill = self._skills.pop(name, None)
        if skill is None:
            return None
        for alias in list(skill.aliases):
            if self._aliases.get(alias) == name:
                self._aliases.pop(alias, None)
        return skill

    def lookup(self, name: str) -> BundledSkillDefinition | None:
        """Resolve a skill by exact name or by alias."""
        skill = self._skills.get(name)
        if skill is not None:
            return skill
        resolved = self._aliases.get(name)
        if resolved is not None:
            return self._skills.get(resolved)
        return None

    async def activate(
        self,
        name: str,
        args: str | None = None,
        context: dict[str, Any] | None = None,
    ) -> str:
        """Activate a skill by name and return its rendered prompt.

        Looks the skill up (by exact name or alias), calls its
        ``get_prompt_for_command`` coroutine with the provided args and
        context, and returns an error string on failure.  The error
        string is returned rather than raising because callers (e.g. the
        agent loop) expect a string result to inject into the prompt.

        Args:
            name: The skill name or alias to activate.
            args: Optional argument string passed to the skill's prompt
                renderer (e.g. ``"{{args}}"`` placeholders are replaced).
            context: Optional context dict whose values are substituted
                into ``{{key}}`` placeholders in the prompt body.

        Returns:
            The rendered prompt string, or an error message when the skill
            is not found or its renderer raises an exception.
        """
        skill = self.lookup(name)
        if skill is None:
            return f"Error: skill '{name}' not found."
        ctx = context or {}
        try:
            prompt = await skill.get_prompt_for_command(args, ctx)
            return prompt
        except Exception as e:
            return f"Error activating skill '{name}': {e}"

    async def activate_for_paths(self, file_paths: list[str]) -> list[str]:
        """Return names of skills whose ``when_to_use`` matches given file extensions.

        Scans each file path for a file-extension match against the skill's
        ``when_to_use`` string (case-insensitive).  Only skills with
        ``auto_activate=True`` are considered.  Each skill name appears at
        most once in the result, regardless of how many matching paths are
        provided, to avoid injecting duplicate prompts into the context.

        Args:
            file_paths: List of absolute or relative file paths to inspect.

        Returns:
            Names of skills that should be auto-activated for the given paths.
        """
        prompts: list[str] = []
        seen: set[str] = set()
        for file_path in file_paths:
            # Extract the trailing extension (e.g. ".py", ".ts") from the path.
            match = _EXTENSIONS_HEADER_PATTERN.search(file_path)
            if match is None:
                continue
            ext = match.group(0).lower()
            for skill in self._skills.values():
                if skill.auto_activate and skill.when_to_use and ext in skill.when_to_use.lower() and skill.name not in seen:
                    seen.add(skill.name)
                    prompts.append(skill.name)
        return prompts

    def load_from_dir(
        self,
        skills_dir: str,
        source: SkillSource = SkillSource.PROJECT,
    ) -> None:
        """Walk a directory and load every ``SKILL.md`` (or frontmatter) file.

        Hidden directories are skipped.  Each discovered file is parsed and
        registered with the supplied :class:`SkillSource`.

        A skill bundle is ``<dir>/<skill-name>/SKILL.md``.  Everything else
        inside that folder (``references/``, ``rules/``, ``adapters/``,
        ``modes/``, sibling ``README.md`` files, ...) is supporting material
        for the *bundle's* skill, not a skill of its own: those documents are
        long, partial, and meaningless on their own, and registering them
        pollutes the catalogue with hundreds of fragments that then crowd out
        the real skills.  Flat ``*.md`` files are therefore only accepted
        directly under ``skills_dir`` (the ``tool-*.md`` guide layout).

        Args:
            skills_dir: Absolute or relative path to the directory to scan.
            source: The :class:`SkillSource` tag applied to every skill
                discovered in this directory.  Defaults to
                :attr:`SkillSource.PROJECT`.
        """
        if not os.path.isdir(skills_dir):
            return
        root_dir = os.path.abspath(skills_dir)
        for root, dirs, files in os.walk(skills_dir):
            dirs[:] = [d for d in dirs if not d.startswith(".")]
            is_root = os.path.abspath(root) == root_dir
            for filename in files:
                if filename.upper() == "SKILL.MD":
                    filepath = os.path.join(root, filename)
                    self._load_skill_md(filepath, source)
            if not is_root:
                continue
            for filename in files:
                if not filename.endswith(".md") or filename.upper() == "SKILL.MD" or filename == "MEMORY.md":
                    continue
                filepath = os.path.join(root, filename)
                # No cheap frontmatter peek here: runtime-encrypted
                # auto-generated skills only reveal their frontmatter after
                # decryption, which happens inside _load_skill_md.  Plain
                # markdown without frontmatter is skipped there as before.
                self._load_skill_md(filepath, source)

    def _load_skill_md(self, filepath: str, source: SkillSource) -> None:
        """Parse a SKILL.md file's frontmatter and register it as a skill.

        Extracts YAML frontmatter (a ``---``-delimited block at the top of
        the file), validates the required ``name`` field, applies the
        lifecycle gate for auto-generated skills, and constructs a
        :class:`BundledSkillDefinition` with all optional fields parsed.

        The ``allowed-tools`` field accepts both space-delimited and
        comma-delimited formats for backwards compatibility with older
        skill files.  The ``aliases`` field similarly accepts YAML lists,
        comma-separated strings, or space-delimited strings.
        """
        content = _read_skill_source(filepath)
        if not content:
            return

        # Parse YAML frontmatter -- supports both standards-compliant YAML
        # and our legacy key: value format (via YAML)
        metadata, body = _parse_yaml_frontmatter(content)
        name = metadata.get("name", "").strip()
        if not name:
            # No name field means this is not a valid skill definition;
            # skip silently to avoid noisy warnings on README-style files.
            return

        # Lifecycle gate: auto-generated skills carry an explicit ``status``
        # and only ``active`` ones may be loaded.  Anything else (proposed,
        # rejected, disabled) is kept on disk for auditing but must never be
        # injected into the prompt.  Skills without a status are unchanged.
        status = str(metadata.get("status", "")).strip().lower()
        if status and status != "active":
            return

        # Validate name per spec: lowercase, hyphens, no underscores.
        # Normalising here ensures that skills with inconsistent casing or
        # underscores in their frontmatter are still discoverable.
        _name_validated = name.lower().replace("_", "-")

        description = str(metadata.get("description", "")).strip()
        license_val = str(metadata.get("license", "")).strip()
        compatibility = str(metadata.get("compatibility", "")).strip()
        when_to_use = str(metadata.get("when_to_use", "")).strip()
        argument_hint = str(metadata.get("argument_hint", "")).strip()
        model = metadata.get("model")
        disable_model = _parse_bool(str(metadata.get("disable_model_invocation", "false")))
        user_invocable = _parse_bool(str(metadata.get("user_invocable", "true")))
        hidden = _parse_bool(str(metadata.get("hidden", "false")))
        auto_activate = _parse_bool(str(metadata.get("auto_activate", "false")))
        context_raw = str(metadata.get("context", "inline")).strip().lower()
        context_enum = SkillContext(context_raw) if context_raw in ("inline", "fork") else SkillContext.INLINE

        # metadata map -- extract any unrecognized keys as extra metadata.
        # Nested ``metadata`` dicts are flattened into a single dict[str, str]
        # so callers can treat metadata as a flat key-value store regardless
        # of how it was structured in the frontmatter.
        extra_meta: dict[str, str] = {}
        meta_val = metadata.get("metadata")
        if isinstance(meta_val, dict):
            extra_meta = {str(k): str(v) for k, v in meta_val.items()}
        # Also flatten top-level extra fields into metadata so that
        # frontmatter keys outside the known set are not lost.
        _known = {"name", "description", "license", "compatibility", "aliases",
                   "allowed-tools", "allowed_tools", "metadata", "model", "context",
                   "when_to_use", "argument_hint", "disable_model_invocation",
                   "user_invocable", "hidden", "auto_activate", "version"}
        for k, v in metadata.items():
            if k not in _known and v is not None:
                extra_meta[str(k)] = str(v)

        # allowed-tools -- support both standard (space-delimited) and legacy (comma)
        # formats.  Space-delimited is the Agent Skills standard; comma format
        # was used by early skill files and is still encountered in the wild.
        allowed_tools_raw = str(metadata.get("allowed-tools") or metadata.get("allowed_tools") or "")
        allowed_tools: list[str] | None = None
        if allowed_tools_raw.strip():
            # Split by spaces, handle entries like "Bash(git:*)" from spec.
            tools_list: list[str] = []
            for part in allowed_tools_raw.split():
                part = part.strip()
                if part:
                    tools_list.append(part)
            # Also support comma format for legacy files where a single
            # space-separated token contains commas.
            if len(tools_list) == 1 and "," in tools_list[0]:
                tools_list = [t.strip() for t in tools_list[0].split(",") if t.strip()]
            if tools_list:
                allowed_tools = tools_list

        # aliases -- support YAML list, comma string, or space-delimited.
        # YAML lists are the preferred format; string formats are accepted
        # for backwards compatibility with older skill files.
        aliases_raw = metadata.get("aliases")
        aliases: list[str] = []
        if isinstance(aliases_raw, list):
            aliases = [str(a).strip() for a in aliases_raw if a]
        elif isinstance(aliases_raw, str) and aliases_raw.strip():
            aliases = [a.strip() for a in _ALIASES_SEPARATOR.split(aliases_raw) if a.strip()]

        async def get_prompt(
            args: str | None = None,
            ctx: dict[str, Any] | None = None,
        ) -> str:
            """Render the skill body by substituting argument and context placeholders.

            Supports ``{{args}}``, ``{{arguments}}``, ``{{user_input}}`` for
            user-supplied arguments and ``{{key}}`` for any context dict entry.
            Placeholders that are not present in the provided context are left
            as-is, allowing skill authors to include optional placeholders
            without breaking the prompt.
            """
            resolved = body
            if args is not None:
                resolved = resolved.replace("{{args}}", args)
                resolved = resolved.replace("{{arguments}}", args)
                resolved = resolved.replace("{{user_input}}", args)
            if ctx is not None:
                for key, value in ctx.items():
                    resolved = resolved.replace(f"{{{{{key}}}}}", str(value))
            return resolved

        skill = BundledSkillDefinition(
            name=_name_validated,
            description=description,
            get_prompt_for_command=get_prompt,
            aliases=aliases,
            when_to_use=when_to_use,
            argument_hint=argument_hint,
            allowed_tools=allowed_tools,
            model=str(model) if model else None,
            disable_model_invocation=disable_model,
            user_invocable=user_invocable,
            hidden=hidden,
            auto_activate=auto_activate,
            context=context_enum,
            source=source,
            file_path=filepath,
            body=body,
            license=license_val,
            compatibility=compatibility,
            metadata=extra_meta,
        )
        self.register(skill)

    def list_all(self) -> list[BundledSkillDefinition]:
        """Return all registered skills."""
        return list(self._skills.values())


def _parse_yaml_frontmatter(content: str) -> tuple[dict[str, Any], str]:
    """Split YAML/legacy frontmatter from a SKILL.md body.

    Matches a ``---``-delimited block at the start of the file and attempts
    to parse it as YAML.  When no frontmatter is present the metadata is
    empty and the whole content is returned as the body.  YAML parse errors
    are caught and replaced with an empty dict so that malformed frontmatter
    does not prevent the rest of the file from being loaded.

    Returns:
        A ``(metadata, body)`` tuple where *metadata* is a dict of parsed
        frontmatter keys and *body* is the remaining markdown content.
    """
    match = _FRONTMATTER_PATTERN.match(content)
    if match is None:
        return {}, content
    frontmatter_text = match.group(1)
    body = content[match.end():]
    try:
        metadata = yaml.safe_load(frontmatter_text) or {}
    except Exception:
        # YAML parse errors (malformed keys, duplicate entries, etc.) are
        # non-fatal; return an empty metadata dict so the file is still
        # usable as a body-only document.
        metadata = {}
    if not isinstance(metadata, dict):
        # YAML can return non-dict types (e.g. a list) for some edge-case
        # inputs; coerce to empty dict to maintain a consistent return type.
        metadata = {}
    return metadata, body


# Public alias reused by sibling modules (e.g. ``encre.commands.registry``)
# so the same frontmatter contract is honoured across skills and commands.
parse_yaml_frontmatter = _parse_yaml_frontmatter


def _parse_bool(value: str) -> bool:
    """Parse a truthy string ("true"/"1"/"yes"/"on") into a boolean.

    Accepts common YAML boolean representations.  Any other value, including
    empty strings, is treated as ``False`` so that unset frontmatter fields
    default to a safe negative rather than raising an exception.

    Args:
        value: The raw string value from the frontmatter, e.g. ``"true"``,
            ``"1"``, ``"yes"``, ``"on"``, or ``"false"``.

    Returns:
        ``True`` for truthy inputs, ``False`` otherwise.
    """
    return value.strip().lower() in ("true", "1", "yes", "on")
